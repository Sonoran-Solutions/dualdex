#!/usr/bin/env python3
"""Exact-ROM numeric map topology only; never emit or decode ROM text."""
import argparse
from pathlib import Path
import re
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / 'tools/rom-evidence'))

import unbound_location as location  # noqa: E402
from unbound_identity import ROM_SHA256 as EVIDENCE_ROM_SHA256, ROM_SIZE, exact_rom  # noqa: E402
from ups_identity import read_local, require  # noqa: E402

ROM_SHA256 = '7aa25bbf568f7cfcf6ee1cf2e9e6ff637350b3d0705c2375cabb6baa7d9739f7'
assert ROM_SHA256 == EVIDENCE_ROM_SHA256, 'identity pin drifted from rom-evidence'
ROWS_SHA256 = 'b1f061cac23143d81ec030b89dc04776219a1e2faac3f5ab3ba1bc8e86c4bfb4'
NAME_TABLE_ADDRESS = 0x083F1CAC
FIRST_SECTION, LAST_SECTION = 0x58, 0xC4
GROUP_COUNT, MAP_COUNT = 57, 645
OUTPUT = ROOT / 'app/src/main/java/com/dualdex/pokemon/unbound/UnboundMapTable.kt'


def rows_for(counts, sections):
    require(len(counts) == GROUP_COUNT and all(type(c) is int and 0 < c <= 256 for c in counts),
            'invalid group counts')
    require(sum(counts) == len(sections) == MAP_COUNT, 'map count mismatch')
    require(all(type(s) is int and FIRST_SECTION <= s <= LAST_SECTION for s in sections),
            'section outside name-table range')
    pairs = [(g, n) for g, count in enumerate(counts) for n in range(count)]
    return [(g, n, section) for (g, n), section in zip(pairs, sections)]


def rows_sha256(rows):
    # Same encoding as unbound_location.enumerate_maps and the committed evidence.
    return location.rowe.digest(b''.join(bytes(row) for row in rows))


def derive(rom):
    exact_rom(rom)  # Before interpreting any offset, including the accessor code.
    path = location.inspect_map_header_path(rom)
    table, key = int(path['map_groups_table'], 16), int(path['group_pointer_xor_key'], 16)
    summary, rows = location.enumerate_maps(rom, table, key)
    names = location.inspect_map_names(rom)  # Numeric metadata/hashes only; no text decoder.
    require((int(names['table'], 16), int(names['first_mapsec'], 16), int(names['last_mapsec'], 16)) ==
            (NAME_TABLE_ADDRESS, FIRST_SECTION, LAST_SECTION), 'name-table contract changed')
    counts, sections = summary['maps_per_group'], [row[2] for row in rows]
    require(rows_for(counts, sections) == rows, 'noncontiguous map rows')
    require(summary['rows_sha256'] == rows_sha256(rows) == ROWS_SHA256, 'pinned rows hash mismatch')
    for group, num, section in ((1, 7, 0x80), (3, 6, 0x93)):
        header = location.map_header(rom, table, key, group, num)
        require(rom[header - location.ROM_BASE + location.MAPSEC_OFFSET] == section, 'runtime spot pin changed')
    return counts, sections


def int_array(values):
    return '\n'.join('        ' + ', '.join(str(v) for v in values[i:i+16]) + ','
                     for i in range(0, len(values), 16))


def render(counts, sections):
    return f'''package com.dualdex.pokemon.unbound

/**
 * VERIFIED exact-ROM numeric topology via unbound_location.py accessor/structural enumeration.
 * No ROM text or town-map geometry. Generated by generate_unbound_map_data.py; DO NOT EDIT.
 * Regenerate with --rom <private-rom>; ROM-free byte-for-byte integrity check: --verify.
 */
internal object UnboundMapTable {{
    const val ROM_SHA256: String = "{ROM_SHA256}"
    const val ROWS_SHA256: String = "{ROWS_SHA256}"
    const val GENERATOR_SHA256: String = "{location.rowe.digest(Path(__file__).read_bytes())}"
    const val NAME_TABLE_ADDRESS: Int = 0x{NAME_TABLE_ADDRESS:08X}
    const val FIRST_SECTION: Int = 0x{FIRST_SECTION:02X}
    const val LAST_SECTION: Int = 0x{LAST_SECTION:02X}
    const val GROUP_COUNT: Int = {GROUP_COUNT}
    const val MAP_COUNT: Int = {MAP_COUNT}

    val GROUP_MAP_COUNTS: IntArray = intArrayOf(
{int_array(counts)}
    )

    private val SECTIONS: IntArray = intArrayOf(
{int_array(sections)}
    )
    private val groupStarts = GROUP_MAP_COUNTS.runningFold(0) {{ total, count -> total + count }}

    fun sectionId(group: Int, num: Int): Int? {{
        if (group !in GROUP_MAP_COUNTS.indices || num < 0 || num >= GROUP_MAP_COUNTS[group]) return null
        return SECTIONS[groupStarts[group] + num]
    }}
}}
'''


def verify(text):
    def array(name):
        match = re.search(rf'val {name}: IntArray = intArrayOf\(\n(.*?)\n    \)', text, re.S)
        require(match is not None, f'missing {name}')
        require(re.fullmatch(r'[\d,\s]+', match[1]) is not None, f'non-numeric {name}')
        return [int(v.strip()) for v in match[1].split(',') if v.strip()]

    counts, sections = array('GROUP_MAP_COUNTS'), array('SECTIONS')
    require(rows_sha256(rows_for(counts, sections)) == ROWS_SHA256, 'pinned rows hash mismatch')
    require(text == render(counts, sections), 'artifact pins/provenance/output mismatch')
    return counts, sections


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', type=Path)
    parser.add_argument('--output', type=Path, default=OUTPUT)
    parser.add_argument('--verify', action='store_true')
    args = parser.parse_args()
    try:
        if args.verify:
            counts, sections = verify(read_local(args.output, 64 * 1024).decode('utf-8'))
            if args.rom:
                require((counts, sections) == derive(read_local(args.rom, ROM_SIZE)), 'ROM derivation differs')
        else:
            require(args.rom is not None, '--rom is required')
            counts, sections = derive(read_local(args.rom, ROM_SIZE))
            for source in (args.rom, Path(__file__)):
                require(args.output.resolve() != source.resolve() and
                        not (args.output.exists() and args.output.samefile(source)),
                        'output must not overwrite an input or tool')
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(render(counts, sections), encoding='utf-8')
        print(f'Unbound map table verified: {len(counts)} groups, {len(sections)} rows, digest {ROWS_SHA256}')
        return 0
    except (ValueError, OSError, UnicodeError, KeyError, TypeError) as error:
        print(f'FAIL: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
